import { describe, expect, it } from 'vitest';
import { existsSync, readFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PNG } from 'pngjs';
import { multiplicationPages } from './multiplication';
import { placeValuePages } from './placeValue';
import { sightWordPages } from './sightWordsContent';
import { cursivePages } from './cursive';
import { loosePages } from './loose';
import { halloweenPages } from './halloween';
import { christmasPages } from './christmas';
import { thanksgivingPages } from './thanksgiving';
import { timesTablePages } from './timesTables';
import { cursiveSentencesPage } from './cursiveSentences';
import { howToCursivePage } from './howToCursive';
import { cursiveLetters } from './cursiveLetters';
import type { PageDef } from './pageTypes';

/**
 * The Google Images channel (PLAN #17 wave 1 pillars + #32 wave 2 + wave 4,
 * the holiday/how-to/times-table batch): pages declare a sheetImage whose
 * src/width/height must match a real PNG in public/images/ (generated by
 * `npm run sheet-images`). A mismatch = broken image or layout shift.
 */
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const WAVE_TWO = [
  // math cluster
  'multiplication-chart-blank',
  'multiplication-chart-1-15',
  'multiplication-chart-1-20',
  'decimal-place-value-chart',
  'place-value-anchor-chart',
  'place-value-chart-printable',
  'hundred-chart',
  'number-line-printable',
  'addition-chart',
  'fraction-chart',
  // halloween cluster
  'halloween-word-search',
  'halloween-color-by-number',
  'halloween-cursive-practice',
];
const PILLARS = [
  'multiplication-chart',
  'place-value-chart',
  'kindergarten-sight-words',
  'cursive-alphabet',
  'alphabet-chart',
];
// Wave 4 (2026-11-03): new-batch 6 + times-table matrix + christmas/thanksgiving
// clusters. The /times-table/ hub has no .printable — nothing to shoot. The
// teaching-calendar year index has a PNG but no PageDef (hand-built page), so
// it is guarded separately below.
const WAVE_FOUR = [
  'place-value-chart-with-periods',
  'cursive-sentences',
  'how-to-write-in-cursive',
  'multiplication-chart-printable',
  'times-table-chart',
  ...Array.from({ length: 12 }, (_, i) => `times-table-${i + 1}`),
  'christmas-word-search',
  'christmas-color-by-number',
  'letter-to-santa',
  'thanksgiving-word-search',
  'thanksgiving-color-by-number',
  'thanksgiving-placemat-printable',
  'i-am-thankful-for-worksheet',
];

const all: PageDef[] = [
  ...multiplicationPages,
  ...placeValuePages,
  ...sightWordPages,
  ...cursivePages,
  ...loosePages,
  ...halloweenPages,
  ...christmasPages,
  ...thanksgivingPages,
  ...timesTablePages,
  cursiveSentencesPage,
  howToCursivePage,
];
const withImages = all.filter((d) => d.sheetImage);

describe('sheetImage (Google Images channel)', () => {
  it('exactly the pillar + wave-2 + wave-4 pages carry a sheet image', () => {
    expect(withImages.map((d) => d.slug).sort()).toEqual([...PILLARS, ...WAVE_TWO, ...WAVE_FOUR].sort());
  });

  for (const def of withImages) {
    it(`${def.slug}: src resolves and declared dimensions match the PNG on disk`, () => {
      const img = def.sheetImage!;
      expect(img.src.startsWith('/images/')).toBe(true);
      expect(img.alt.endsWith('.')).toBe(true);
      expect(img.alt.length).toBeGreaterThan(60);
      const file = resolve(ROOT, 'public', img.src.slice(1));
      expect(existsSync(file), `${img.src} missing — run npm run sheet-images`).toBe(true);
      const png = PNG.sync.read(readFileSync(file));
      expect(png.width, 'width must match the generated PNG (rerun npm run sheet-images)').toBe(img.width);
      expect(png.height, 'height must match the generated PNG (rerun npm run sheet-images)').toBe(img.height);
    });
  }
});

describe('cursive letter matrix sheet images (#32 wave 2)', () => {
  it('all 26 letters carry a letter-specific worksheet PNG with a distinct alt', () => {
    expect(cursiveLetters).toHaveLength(26);
    const srcs = new Set(cursiveLetters.map((d) => d.sheetImage!.src));
    const alts = new Set(cursiveLetters.map((d) => d.sheetImage!.alt));
    expect(srcs.size).toBe(26);
    expect(alts.size).toBe(26);
  });

  for (const def of cursiveLetters) {
    it(`/cursive/${def.slug}/: declared dimensions match the PNG on disk`, () => {
      const img = def.sheetImage!;
      expect(img.src).toBe(`/images/cursive-letter-${def.slug}-worksheet.png`);
      expect(img.alt.endsWith('.')).toBe(true);
      expect(img.alt.length).toBeGreaterThan(60);
      expect(img.alt).toContain(def.sheet.capital);
      const file = resolve(ROOT, 'public', img.src.slice(1));
      expect(existsSync(file), `${img.src} missing — run npm run sheet-images`).toBe(true);
      const png = PNG.sync.read(readFileSync(file));
      expect(png.width).toBe(img.width);
      expect(png.height).toBe(img.height);
    });
  }
});

/**
 * The Download PNG button (PLAN #18): the toolbar anchor is driven purely by
 * sheetImage, so these dist guards only run after a build (their order in the
 * release flow is build → vitest). They pin the mobile path — no Ctrl+P on a
 * phone, download-then-print is the real journey.
 */
const DIST = resolve(ROOT, 'dist');
const pillarDistReady =
  withImages.every((d) => existsSync(resolve(DIST, (d.path ?? d.slug).replace(/^\//, ''), 'index.html'))) &&
  existsSync(resolve(DIST, 'cursive', 'a', 'index.html'));

describe.skipIf(!pillarDistReady)('Download PNG button (PLAN #18)', () => {
  for (const def of withImages) {
    it(`${def.slug}: built page exposes its sheet PNG as a download`, () => {
      const html = readFileSync(resolve(DIST, (def.path ?? def.slug).replace(/^\//, ''), 'index.html'), 'utf8');
      expect(
        new RegExp(`href="${def.sheetImage!.src.replace(/\//g, '\\/')}"[^>]*\\bdownload\\b`).test(html),
        'toolbar must carry <a href="…" download> for the sheet PNG',
      ).toBe(true);
    });
  }

  for (const def of cursiveLetters) {
    it(`/cursive/${def.slug}/: built page exposes its sheet PNG as a download`, () => {
      const html = readFileSync(resolve(DIST, 'cursive', def.slug, 'index.html'), 'utf8');
      expect(
        new RegExp(`href="${def.sheetImage!.src.replace(/\//g, '\\/')}"[^>]*\\bdownload\\b`).test(html),
        'toolbar must carry <a href="…" download> for the sheet PNG',
      ).toBe(true);
    });
  }

  it('a page without a sheet image carries no download anchor', () => {
    const html = readFileSync(resolve(DIST, 'sign-in-sheet', 'index.html'), 'utf8');
    expect(html).not.toContain('<a class="btn" href="/images/');
  });
});

/**
 * The teaching-calendar year index carries a sheet PNG too, but the page is
 * hand-built (no PageDef), so its wiring lives inline in the .astro template.
 */
describe('teaching-calendar year-index sheet image (wave 4, no PageDef)', () => {
  const png = resolve(ROOT, 'public', 'images', 'teaching-calendar-year-index.png');

  it('the PNG exists at its declared dimensions', () => {
    expect(existsSync(png), 'missing — run npm run sheet-images').toBe(true);
    const img = PNG.sync.read(readFileSync(png));
    expect(img.width).toBe(2016);
    expect(img.height).toBe(1568);
  });

  it('the built page wires it as a download and a preview figure', () => {
    const html = readFileSync(resolve(DIST, 'teaching-calendar', 'index.html'), 'utf8');
    expect(html).toContain('href="/images/teaching-calendar-year-index.png" download');
    expect(html).toContain('sheet-preview');
    expect(html).toContain('src="/images/teaching-calendar-year-index.png"');
  });
});
