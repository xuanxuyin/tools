/**
 * Image-forward variant card (the incumbent image-wall pattern: Superstar
 * serves ~20 product blocks per page, DadsWorksheets' hubs are card walls —
 * every sibling printable is surfaced as a real preview, never plain text).
 * Reuses the PNGs `npm run sheet-images` already generates.
 */
export interface VariantCard {
  /** Internal URL with trailing slash, e.g. '/multiplication-chart-blank/'. */
  href: string;
  title: string;
  /** One-line reason a teacher picks this version. */
  blurb: string;
  img: { src: string; alt: string; width: number; height: number };
  /**
   * 'cover' for very tall multi-sheet pack PNGs (height/width ≳ 1.6): in a
   * 4:3 contain box they shrink to a near-blank ghost, so the card shows the
   * top of the first sheet at legible size instead (DadsWorksheets-style
   * first-page preview). Undefined = contain.
   */
  fit?: 'cover';
}

/** Contract shared by every printable page (same role as tintbrew's ScenarioDef). */
export interface PageDef {
  /** Flat URL slug, e.g. 'place-value-chart' -> /place-value-chart/ */
  slug: string;
  /** Full route path when it is not `/${slug}` — cursive letters live at /cursive/<slug>/. */
  path?: string;
  /** Which hub owns the page (drives breadcrumb + footer grouping). */
  hub:
    | 'charts'
    | 'sight-words'
    | 'cursive'
    | 'graph-paper'
    | 'halloween'
    | 'thanksgiving'
    | 'christmas'
    | 'sign-in-sheets'
    | 'cootie'
    | 'coloring';
  h1: string;
  metaTitle: string;
  metaDescription: string;
  lead: string;
  introHeading: string;
  /** Hand-written teaching facts — the anti-thin-content layer. */
  intro: string[];
  /** Optional second prose block (cursive letters: the "capital X in cursive" deep-dive). */
  extraSection?: { heading: string; paras: string[] };
  /** Small print hint above the sheet, e.g. 'Fits one letter page, portrait.' */
  printNote: string;
  tips: { title: string; body: string }[];
  faqs: { q: string; a: string }[];
  related: { href: string; label: string }[];
  /** Interactive printable -> also gets WebApplication JSON-LD. */
  interactive?: boolean;
  /** Fold/make steps -> HowTo JSON-LD (4/5 incumbent cootie pages lack it). */
  howTo?: { name: string; steps: { name: string; text: string }[] };
  /**
   * In-content preview image of the printable itself — the Google Images
   * channel (page HTML is a table/SVG otherwise, which image search can't
   * index). Generated by `npm run sheet-images`; src/width/height must match
   * the PNG on disk (guarded by sheetImages.test.ts).
   */
  sheetImage?: {
    src: string;
    alt: string;
    width: number;
    height: number;
    caption?: string;
  };
  /** Wide sheets (1-20 grids, number lines) print landscape. */
  landscape?: boolean;
  /**
   * Image cards of sibling printables in the same family — rendered by
   * ChartPage between the page body and the related-links section. Excludes
   * the page's own URL (a card never links to itself).
   */
  variants?: VariantCard[];
}
